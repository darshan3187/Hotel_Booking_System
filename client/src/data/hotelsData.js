// Helper functions for data lookup & filtering

export const getHotelById = (id) => {
  if (!id) return HOTELS_DATA[0];
  const found = HOTELS_DATA.find((h) => h._id === String(id) || h.id === String(id));
  return found || HOTELS_DATA[0];
};

export const getRoomById = (roomId) => {
  if (!roomId) return { ...HOTELS_DATA[0].rooms[0], hotelId: HOTELS_DATA[0] };
  for (const hotel of HOTELS_DATA) {
    if (hotel.rooms) {
      const room = hotel.rooms.find((r) => r._id === String(roomId) || r.id === String(roomId));
      if (room) {
        return {
          ...room,
          hotelId: {
            _id: hotel._id,
            name: hotel.name,
            city: hotel.city,
            location: hotel.location
          }
        };
      }
    }
  }
  return { ...HOTELS_DATA[0].rooms[0], hotelId: HOTELS_DATA[0] };
};

export const filterHotels = (filters = {}) => {
  let list = [...HOTELS_DATA];

  const { city, search, minPrice, maxPrice, rating, roomType, sortBy } = filters;

  if (city) {
    list = list.filter((h) => h.city.toLowerCase().includes(city.toLowerCase().trim()));
  }

  if (search) {
    const term = search.toLowerCase().trim();
    list = list.filter(
      (h) =>
        h.name.toLowerCase().includes(term) ||
        h.city.toLowerCase().includes(term) ||
        h.location.toLowerCase().includes(term) ||
        h.description.toLowerCase().includes(term)
    );
  }

  if (minPrice) {
    list = list.filter((h) => h.startingPrice >= Number(minPrice));
  }

  if (maxPrice) {
    list = list.filter((h) => h.startingPrice <= Number(maxPrice));
  }

  if (rating) {
    list = list.filter((h) => h.rating >= Number(rating));
  }

  if (roomType) {
    list = list.filter((h) =>
      h.rooms && h.rooms.some((r) => r.roomType.toLowerCase().includes(roomType.toLowerCase()))
    );
  }

  if (sortBy === 'price-low') {
    list.sort((a, b) => a.startingPrice - b.startingPrice);
  } else if (sortBy === 'price-high') {
    list.sort((a, b) => b.startingPrice - a.startingPrice);
  } else if (sortBy === 'rating') {
    list.sort((a, b) => b.rating - a.rating);
  }

  return list;
};
